const key = (s: string) => s.normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/[^A-Za-z0-9]+/g, ' ').trim().toLowerCase();
const byKey = new Map(unescoCountries.map(n => [key(n), n]));
/** The UNESCO name for a country value, including names stored in another spelling; '' when not in the list. */
export function unescoCountry(value: string): string {
  return byKey.get(key(value || '')) || legacyNames[key(value || '')] || '';
}
